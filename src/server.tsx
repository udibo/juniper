/**
 * This module contains the server-side runtime for Juniper applications.
 *
 * It provides the {@linkcode createServer} function for creating Hono applications
 * with integrated routing, static file serving, and server-side rendering.
 *
 * @module
 */
import * as path from "@std/path";
import { HttpError } from "./mod.ts";
import { Hono } from "hono";
import type { Schema } from "hono";
import { etag } from "hono/etag";
import { trimTrailingSlash } from "hono/trailing-slash";
import { RouterContextProvider } from "react-router";

import type { Client } from "./client.tsx";
import { getInstance } from "./utils/otel.ts";

import {
  buildApp,
  createHandlers,
  getBuildId,
  isRedirectResponse,
  mergeServerRoutes,
  toRedirectEnvelope,
} from "./_server.tsx";
import type { AppEnv, Route } from "./_server.tsx";

export type {
  AppEnv,
  Route,
  ServerMainRouteModule,
  ServerRouteModule,
} from "./_server.tsx";

function varyByRoute(headers: Headers): void {
  const names = new Set(
    (headers.get("Vary") ?? "").split(",").map((name) =>
      name.trim().toLowerCase()
    )
      .filter(Boolean),
  );
  if (names.has("*")) return;
  names.add("accept");
  names.add("x-juniper-route-id");
  headers.set("Vary", [...names].join(", "));
}

/**
 * Creates the Hono application from generated client and server route trees.
 *
 * `Builder` normally writes this call into `main.ts`; customize behavior in route
 * modules instead of editing generated files. Each request gets a fresh router
 * context. Hono middleware runs before SSR or route-data handlers. Errors denied
 * by middleware render without invoking loaders. Responses vary by `Accept` and
 * `X-Juniper-Route-Id` while retaining application cache variation.
 *
 * @param moduleUrl - File URL of the application entrypoint; its directory owns `public/`.
 * @param client - Matching client route definitions from the same build.
 * @param route - Server route tree, normally generated by Builder.
 * @returns A Hono app usable through `fetch` or `request`; this does not open a listener.
 * @example
 * ```tsx
 * import { Client } from "@udibo/juniper/client";
 * import { createServer } from "@udibo/juniper/server";
 *
 * const client = new Client({
 *   path: "/",
 *   main: { default: () => <h1>Hello</h1> },
 * });
 * export const server = createServer(import.meta.url, client, { path: "/" });
 * if (import.meta.main) Deno.serve(server.fetch);
 * ```
 */
export function createServer<
  E extends AppEnv = AppEnv,
  S extends Schema = Schema,
  BasePath extends string = "/",
>(
  moduleUrl: string,
  client: Client,
  route: Route<E, S, BasePath>,
): Hono<E, S, BasePath> {
  const projectRoot = path.dirname(path.fromFileUrl(moduleUrl));
  const appWrapper = new Hono<E, S, BasePath>({ strict: true });

  appWrapper.use(async (c, next) => {
    c.set("context", new RouterContextProvider());
    const buildId = await getBuildId(projectRoot);
    if (buildId) c.set("buildId", buildId);
    await next();
    const isDataRequest = c.req.header("X-Juniper-Route-Id") !== undefined;
    // Data-mode requests (with `X-Juniper-Route-Id`) expect a redirect envelope, not a raw 3xx that `fetch` would silently follow.
    if (isDataRequest && isRedirectResponse(c.res)) {
      c.res = toRedirectEnvelope(c.res);
      c.res.headers.delete("Location");
      c.res.headers.delete("X-Remix-Reload-Document");
    }
    if (isDataRequest && buildId) {
      try {
        c.res.headers.set("X-Juniper-Build", buildId);
      } catch {
        c.res = new Response(c.res.body, c.res);
        c.res.headers.set("X-Juniper-Build", buildId);
      }
    }
    try {
      varyByRoute(c.res.headers);
    } catch {
      c.res = new Response(c.res.body, c.res);
      varyByRoute(c.res.headers);
    }
  });

  appWrapper.use(trimTrailingSlash());

  appWrapper.use("/build/main.js", etag(), async (c, next) => {
    c.header("Cache-Control", "private, no-cache, must-revalidate, max-age=0");
    await next();
  });
  appWrapper.use("/build/*", async (c, next) => {
    const pathname = new URL(c.req.url).pathname;
    if (pathname !== "/build/main.js") {
      c.header("Cache-Control", "public, max-age=14400");
    }
    await next();
  });

  appWrapper.onError((cause) => {
    if (
      !(cause instanceof HttpError) &&
      cause !== null &&
      typeof cause === "object" &&
      "getResponse" in cause &&
      typeof cause.getResponse === "function"
    ) {
      console.error(cause);
      return cause.getResponse();
    }
    const error = HttpError.from(cause);
    if (!error.instance) {
      const instance = getInstance();
      if (instance) {
        error.instance = instance;
      }
    }
    console.error(error);
    return error.getResponse();
  });

  const serverRoutes = mergeServerRoutes(route, client.routeObjects);
  const { handlers, errorHandler } = createHandlers(
    route,
    serverRoutes,
    client.htmlProps,
  );
  const app = buildApp(
    route,
    client.rootRoute,
    handlers,
    projectRoot,
    "/",
    errorHandler,
  );

  appWrapper.route("/", app);
  return appWrapper;
}
